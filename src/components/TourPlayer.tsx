const MCP_LINK = "hedgepredict.co/api/mcp";

/** Two beats: paste the link into the AI's connector settings ("Paste one link"), then ask ("then just ask"). */
function Ai({ lt }: { lt: number }) {
  const paste = beat("paste");
  const asked = beat("ask");
  if (lt < asked) {
    const link = MCP_LINK.slice(0, Math.max(0, Math.floor((lt - paste) / 28)));
    return (
      <div className="ts-card ts-connect">
        <span className="ts-k">Connect your AI</span>
        <small className="ts-connect-k">Your AI · Settings · Add connector</small>
        <p className="ts-connect-url">{link || <span className="ts-connect-ph">Paste a link</span>}</p>
        <p className={`ts-connect-ok${on(lt, paste + MCP_LINK.length * 28 + 300)}`}>Connected to HedgePredict</p>
      </div>
    );
  }
  const ask = "Any good plays tonight?";
  const typed = ask.slice(0, Math.max(0, Math.floor((lt - asked) / 30)));
  return (
    <div className="ts-card ts-chat">
      <span className="ts-k">Connect your AI</span>
      <p className="ts-bub is-you">{typed || " "}</p>
      <p className={`ts-bub is-ai${on(lt, asked + 1100)}`}>
        HedgePredict&apos;s recommendation: <b className="is-wager">Kentucky at 43¢ (Wager).</b> It&apos;s 66% sure that price is too cheap. Everything else on tonight&apos;s board looks priced about
        right.
      </p>
    </div>
  );
}

